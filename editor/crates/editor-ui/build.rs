//! Generates the theme from `editor/design/tokens.json`.
//!
//! The token file is a copy of the Claude Design system "Arc Editor". Generating the Rust
//! constants here, at build time, is what keeps the design and the code from drifting apart:
//! there is no second place where a colour or a size is written down.

use std::{env, fmt::Write as _, fs, path::PathBuf};

use serde_json::Value;

#[path = "src/theme/token_parse.rs"]
mod token_parse;

use token_parse::{const_name, parse_color, parse_px, TokenColor};

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let tokens_path = manifest.join("../../design/tokens.json");
    println!("cargo::rerun-if-changed={}", tokens_path.display());
    println!("cargo::rerun-if-changed=src/theme/token_parse.rs");

    let text = fs::read_to_string(&tokens_path)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", tokens_path.display()));
    let tokens: Value = serde_json::from_str(&text)
        .unwrap_or_else(|error| panic!("{} is not JSON: {error}", tokens_path.display()));

    let mut out =
        String::from("// Generated by build.rs from editor/design/tokens.json. Do not edit.\n\n");

    // Colours: one theme for now; the first theme's id is the key of each value.
    let theme = tokens["color"]["themes"][0]["id"]
        .as_str()
        .expect("color.themes[0].id");
    out.push_str("/// Colours of the first theme of the token file.\npub mod color {\n    use super::TokenColor;\n\n");
    let mut all = String::new();
    let mut names = String::new();
    for token in list(&tokens, "color") {
        let name = token["name"].as_str().expect("a colour token has a name");
        let value = match &token["value"] {
            Value::String(value) => value.as_str(),
            by_theme => by_theme[theme]
                .as_str()
                .unwrap_or_else(|| panic!("colour token {name} has no value for theme {theme}")),
        };
        let color = parse_color(value)
            .unwrap_or_else(|| panic!("colour token {name}: cannot read the value {value:?}"));
        let literal = match color {
            TokenColor::Oklch { l, c, h, a } => {
                format!("TokenColor::Oklch {{ l: {l:?}, c: {c:?}, h: {h:?}, a: {a:?} }}")
            }
            TokenColor::Srgb8 { r, g, b, a } => {
                format!("TokenColor::Srgb8 {{ r: {r}, g: {g}, b: {b}, a: {a} }}")
            }
        };
        doc(&mut out, token);
        writeln!(
            out,
            "    pub const {}: TokenColor = {literal};",
            const_name(name)
        )
        .unwrap();
        writeln!(all, "    (\"{name}\", color::{}),", const_name(name)).unwrap();
        writeln!(
            names,
            "    pub const {}: &str = \"arc.{name}\";",
            const_name(name)
        )
        .unwrap();
    }
    out.push_str("}\n\n");
    writeln!(
        out,
        "/// The name each colour has in the toolkit's theme table: `arc.` and the token's name.\npub mod theme_key {{\n{names}}}\n"
    )
    .unwrap();
    writeln!(
        out,
        "/// Every colour token by the name it has in the design system.\npub const COLORS: &[(&str, TokenColor)] = &[\n{all}];\n"
    )
    .unwrap();

    // Lengths: spacing, radius and fixed sizes, all in logical pixels.
    for family in ["spacing", "radius", "size"] {
        writeln!(
            out,
            "/// The `{family}` tokens, in logical pixels.\npub mod {family} {{"
        )
        .unwrap();
        for token in list(&tokens, family) {
            let name = token["name"].as_str().expect("a token has a name");
            let value = token["value"].as_str().unwrap_or_default();
            let px = parse_px(value).unwrap_or_else(|| {
                panic!("{family} token {name}: cannot read the length {value:?}")
            });
            doc(&mut out, token);
            writeln!(out, "    pub const {}: f32 = {px:?};", const_name(name)).unwrap();
        }
        out.push_str("}\n\n");
    }

    // Text styles.
    out.push_str("/// The text styles of the token file.\npub mod text {\n    use super::{TextFamily, TextStyle};\n\n");
    for group in tokens["type"]["groups"].as_array().expect("type.groups") {
        let family = match group["family"].as_str() {
            Some("mono") => "TextFamily::Mono",
            _ => "TextFamily::Sans",
        };
        for style in group["styles"].as_array().expect("a type group has styles") {
            let name = style["name"].as_str().expect("a text style has a name");
            let length = |key: &str| {
                style[key]
                    .as_str()
                    .and_then(parse_px)
                    .unwrap_or_else(|| panic!("text style {name}: cannot read {key}"))
            };
            let weight = style["fontWeight"].as_u64().unwrap_or(400);
            doc(&mut out, style);
            writeln!(
                out,
                "    pub const {}: TextStyle = TextStyle {{ family: {family}, size: {:?}, line_height: {:?}, weight: {weight} }};",
                const_name(name),
                length("fontSize"),
                length("lineHeight"),
            )
            .unwrap();
        }
    }
    out.push_str("}\n");

    let target = PathBuf::from(env::var_os("OUT_DIR").expect("set by cargo")).join("tokens.rs");
    fs::write(&target, out)
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", target.display()));
}

fn list<'a>(tokens: &'a Value, family: &str) -> &'a [Value] {
    tokens[family]["tokens"]
        .as_array()
        .unwrap_or_else(|| panic!("the token file has no list {family}.tokens"))
}

/// The token's usage note as the constant's documentation.
fn doc(out: &mut String, token: &Value) {
    if let Some(usage) = token["usage"].as_str() {
        writeln!(out, "    /// {}", usage.replace('\n', " ")).unwrap();
    }
}
